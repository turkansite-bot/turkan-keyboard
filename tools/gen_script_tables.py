#!/usr/bin/env python3
"""Single source of truth for the Latin <-> Arabic-script conversion tables.

Generates:
  app/src/main/java/com/turkanyazi/keyboard/ScriptTables.kt   (Android)
  tools/out/script-tables.js                                  (embedded in web/index.html)

Edit the tables here, run `python3 tools/gen_script_tables.py`, commit the outputs.
Profile v0.3: one Latin letter -> one Arabic-script character (reversible for the
Azerbaijani alphabet); extra Arabic-script letters, digits, punctuation and
diacritics are mapped one-way when converting back to Latin.
"""
import os

# --- Latin -> Arabic script (the project's reversible letter profile) -------
L2A = {
    'a': '\u0627', '\u0259': '\u06D5', 'b': '\u0628', 'c': '\u062C', '\u00E7': '\u0686',
    'd': '\u062F', 'e': '\u0647', 'f': '\u0641', 'g': '\u06AF', '\u011F': '\u063A',
    'h': '\u06BE', 'x': '\u062E', '\u0131': '\u0649', 'i': '\u06CC', 'j': '\u0698',
    'k': '\u06A9', 'q': '\u0642', 'l': '\u0644', 'm': '\u0645', 'n': '\u0646',
    'o': '\u0648', '\u00F6': '\u0624', 'p': '\u067E', 'r': '\u0631', 's': '\u0633',
    '\u015F': '\u0634', 't': '\u062A', 'u': '\u06C7', '\u00FC': '\u06C6', 'v': '\u06CB',
    'w': '\u06CB',  # one-way: w is not an Azerbaijani letter (loanwords only)
    'y': '\u064A', 'z': '\u0632',
}

# Input folding: look-alike or ASCII-substitute letters people really type/paste.
FOLD = {
    '\u0219': '\u015F', '\u0218': '\u015E',   # ș Ș (comma below)  -> ş Ş
    '\u01DD': '\u0259', '\u018E': '\u018F',   # ǝ Ǝ (turned e)    -> ə Ə
    '\u00E4': '\u0259', '\u00C4': '\u018F',   # ä Ä (ASCII-era ə)  -> ə Ə
}

# Plain punctuation that has an Arabic-script form (comma is context-sensitive).
P2A = {';': '\u061B', '?': '\u061F', '%': '\u066A'}

# --- Arabic script -> Latin -------------------------------------------------
A2L = {v: k for k, v in L2A.items() if k != 'w'}
A2L.update({
    # alef family, hamza, ain
    '\u0622': 'a', '\u0623': 'a', '\u0625': 'a', '\u0671': 'a',
    '\u0621': '', '\u0639': '\u0259', '\u0626': 'i',
    # heh family, ta marbuta
    '\u06C0': '\u0259', '\u06C1': 'h', '\u0629': 't',
    # Arabic/Persian loan letters, adapted the usual Turkic way
    '\u062B': 's', '\u062D': 'h', '\u0630': 'z', '\u0635': 's',
    '\u0636': 'z', '\u0637': 't', '\u0638': 'z',
    # letter variants
    '\u0643': 'k', '\u06AA': 'k', '\u06AD': 'ng', '\u06B5': 'l', '\u06A4': 'v',
    '\u06D0': 'e', '\u06CE': 'e', '\u06D2': 'y',
    # punctuation and separators
    '\u060C': ',', '\u061B': ';', '\u061F': '?', '\u066A': '%',
    '\u066B': ',', '\u066C': '.', '\u06D4': '.', '\u066D': '*',
})

# Ranges removed when converting to Latin: harakat, tatweel, Quranic marks, ZWNJ/ZWJ.
DROP = [(0x064B, 0x065F), (0x0670, 0x0670), (0x0640, 0x0640), (0x06D6, 0x06DC),
        (0x06DF, 0x06E4), (0x06E7, 0x06E8), (0x06EA, 0x06ED), (0x200C, 0x200D)]


def esc(s):
    return ''.join('\\u%04X' % ord(c) for c in s)


def kt_map(name, d, char_key=True, char_val=False):
    items = []
    for k, v in sorted(d.items()):
        key = "'%s'" % esc(k)
        val = ("'%s'" if char_val else '"%s"') % esc(v)
        items.append('        %s to %s' % (key, val))
    return '    val %s: Map<Char, %s> = mapOf(\n%s\n    )\n' % (
        name, 'Char' if char_val else 'String', ',\n'.join(items))


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    kt = ['package com.turkanyazi.keyboard', '',
          '// GENERATED by tools/gen_script_tables.py - do not edit by hand.',
          'internal object ScriptTables {',
          kt_map('latinFold', FOLD, char_val=True),
          kt_map('latinToArabic', L2A),
          kt_map('punctToArabic', P2A),
          kt_map('arabicToLatin', A2L),
          '    val dropRanges: List<CharRange> = listOf(\n' + ',\n'.join(
              "        '%s'..'%s'" % (esc(chr(a)), esc(chr(b))) for a, b in DROP) + '\n    )',
          '}', '']
    path = os.path.join(root, 'app/src/main/java/com/turkanyazi/keyboard/ScriptTables.kt')
    open(path, 'w', encoding='utf-8').write('\n'.join(kt))

    def js_obj(d):
        return '{' + ','.join("'%s':'%s'" % (esc(k), esc(v)) for k, v in sorted(d.items())) + '}'
    js = ('/* GENERATED by tools/gen_script_tables.py */\n'
          'const T={fold:%s,\nl2a:%s,\np2a:%s,\na2l:%s,\ndrop:%s};\n') % (
        js_obj(FOLD), js_obj(L2A), js_obj(P2A), js_obj(A2L),
        '[' + ','.join('[%d,%d]' % r for r in DROP) + ']')
    os.makedirs(os.path.join(root, 'tools/out'), exist_ok=True)
    open(os.path.join(root, 'tools/out/script-tables.js'), 'w', encoding='utf-8').write(js)
    print('letters', len(L2A), 'arabic->latin', len(A2L))


if __name__ == '__main__':
    main()
